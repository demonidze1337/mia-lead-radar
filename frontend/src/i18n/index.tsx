interface I18nValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: MessageKey) => string;
  dir: 'ltr' | 'rtl';
}

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = 'mia_ui_language';

function detectLanguage(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && LANGUAGES.some((item) => item.code === saved)) return saved as Language;
  } catch {
    // Storage can be unavailable in private browser contexts.
  }
  try {
    const telegramLang = WebApp.initDataUnsafe?.user?.language_code;
    if (telegramLang) {
      const base = telegramLang.split('-')[0] as Language;
      if (LANGUAGES.some((item) => item.code === base)) return base;
    }
  } catch {
    // WebApp may not be initialized outside Telegram.
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language.split('-')[0] : 'en';
  return (LANGUAGES.some((item) => item.code === nav) ? nav : 'en') as Language;
}

